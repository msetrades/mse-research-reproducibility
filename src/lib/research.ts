export type ResearchRun = {
  id: string;
  study: string;
  field: string;
  question: string;
  protocol: string;
  dataSource: string;
  dataVersion: string;
  codeUrl: string;
  commit: string;
  environment: string;
  seed: string;
  metric: string;
  value: number;
  unit: string;
  limitations: string;
  artifactUrl: string;
  createdAt: string;
  fingerprint: string;
};

export type SensitivityEntry = {
  id: string;
  study: string;
  factor: string;
  unit: string;
  baselineInput: number;
  lowInput: number;
  highInput: number;
  baselineOutput: number;
  lowOutput: number;
  highOutput: number;
  createdAt: string;
};

export type ResearchArchive = { version: 1; exportedAt: string; runs: ResearchRun[]; sensitivity: SensitivityEntry[] };

export function stableStringify(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(",")}]`;
  if (value && typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>).sort(([a], [b]) => a.localeCompare(b));
    return `{${entries.map(([key, item]) => `${JSON.stringify(key)}:${stableStringify(item)}`).join(",")}}`;
  }
  return JSON.stringify(value) ?? "null";
}

export async function fingerprintRun(run: Omit<ResearchRun, "fingerprint">): Promise<string> {
  const bytes = new TextEncoder().encode(stableStringify(run));
  const digest = await crypto.subtle.digest("SHA-256", bytes);
  return Array.from(new Uint8Array(digest), (byte) => byte.toString(16).padStart(2, "0")).join("");
}

export function completeness(run: Omit<ResearchRun, "id" | "createdAt" | "fingerprint">): { score: number; missing: string[] } {
  const fields: [string, string][] = [
    ["Research question", run.question], ["Protocol / method", run.protocol], ["Data source", run.dataSource],
    ["Data version", run.dataVersion], ["Code or notebook link", run.codeUrl], ["Code commit", run.commit],
    ["Environment", run.environment], ["Random seed", run.seed], ["Outcome metric", run.metric], ["Limitations", run.limitations],
  ];
  const missing = fields.filter(([, value]) => !value.trim()).map(([name]) => name);
  return { score: Math.round(((fields.length - missing.length) / fields.length) * 100), missing };
}

export function sensitivityEffect(entry: Pick<SensitivityEntry, "baselineInput" | "lowInput" | "highInput" | "baselineOutput" | "lowOutput" | "highOutput">) {
  const inputSpan = Math.abs(entry.highInput - entry.lowInput);
  const outputSpan = entry.highOutput - entry.lowOutput;
  const relative = entry.baselineOutput === 0 ? null : ((entry.highOutput - entry.lowOutput) / Math.abs(entry.baselineOutput)) * 100;
  return { absoluteOutputSpan: outputSpan, inputSpan, relativeOutputSpanPct: relative };
}

export function buildArchive(runs: ResearchRun[], sensitivity: SensitivityEntry[]): ResearchArchive {
  return { version: 1, exportedAt: new Date().toISOString(), runs, sensitivity };
}

export function validateArchive(value: unknown): ResearchArchive {
  if (!value || typeof value !== "object") throw new Error("Archive must be a JSON object.");
  const archive = value as Partial<ResearchArchive>;
  if (archive.version !== 1 || !Array.isArray(archive.runs) || !Array.isArray(archive.sensitivity)) {
    throw new Error("This file is not a supported ResearchTrace archive (version 1).");
  }
  if (archive.runs.some((run) => !run || typeof run.id !== "string" || typeof run.study !== "string" || typeof run.fingerprint !== "string")) {
    throw new Error("The archive contains an invalid research run.");
  }
  if (archive.sensitivity.some((entry) => !entry || typeof entry.id !== "string" || typeof entry.factor !== "string")) {
    throw new Error("The archive contains an invalid sensitivity entry.");
  }
  return archive as ResearchArchive;
}

export function reportMarkdown(run: ResearchRun): string {
  return `# ${run.study}\n\n**Field:** ${run.field}\n**Recorded:** ${run.createdAt}\n**Run fingerprint (SHA-256):** \`${run.fingerprint}\`\n\n## Research question\n${run.question}\n\n## Protocol\n${run.protocol}\n\n## Data provenance\n- Source: ${run.dataSource}\n- Version / snapshot: ${run.dataVersion}\n\n## Implementation\n- Code: ${run.codeUrl || "Not recorded"}\n- Commit: ${run.commit || "Not recorded"}\n- Environment: ${run.environment || "Not recorded"}\n- Random seed: ${run.seed || "Not recorded"}\n\n## Result\n**${run.metric}:** ${run.value} ${run.unit}\n\n## Limitations\n${run.limitations}\n\n## Artifact\n${run.artifactUrl || "No artifact link recorded"}\n\n---\nGenerated by ResearchTrace. A fingerprint identifies the recorded metadata; it does not prove the underlying experiment was executed as described.\n`;
}
